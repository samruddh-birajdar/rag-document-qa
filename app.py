"""
RAG Document Question Answering System

A Retrieval-Augmented Generation (RAG) application that lets you upload a PDF
and ask questions about its content. Answers are generated by Gemini 3.8 Flash
using only the retrieved context from the document, with page-level citations.
"""

import os
import time
from google import genai
from dotenv import load_dotenv

import streamlit as st
import PyPDF2
import faiss
import numpy as np
from sentence_transformers import SentenceTransformer

load_dotenv()
client = genai.Client(api_key=os.getenv("GEMINI_API_KEY"))

# Default similarity threshold
SIMILARITY_THRESHOLD = 0.3

# ---------- PDF handling ----------

def extract_text_with_pages(pdf_file):
    """Return a list of (page_number, page_text) tuples."""
    pages = []
    try:
        reader = PyPDF2.PdfReader(pdf_file)
        for page_number, page in enumerate(reader.pages, start=1):
            page_text = page.extract_text()
            if page_text:
                pages.append((page_number, page_text))
    except Exception as e:
        st.error(f"Error while reading PDF: {e}")
    return pages


def split_pages_into_chunks(pages, chunk_size=500, overlap=100):
    """Chunk each page separately so we can track source pages."""
    chunks = []
    chunk_pages = []

    for page_number, page_text in pages:
        start = 0
        while start < len(page_text):
            end = start + chunk_size
            chunk = page_text[start:end]
            if chunk.strip():
                chunks.append(chunk)
                chunk_pages.append(page_number)
            start = end - overlap

    return chunks, chunk_pages


# ---------- Embeddings + vector store ----------

@st.cache_resource
def load_embedding_model():
    return SentenceTransformer("all-MiniLM-L6-v2")


def build_vector_index(chunks, embedding_model):
    embeddings = embedding_model.encode(chunks)
    embeddings = np.array(embeddings).astype("float32")
    index = faiss.IndexFlatL2(embeddings.shape[1])
    index.add(embeddings)
    return index


def retrieve_top_chunks(question, chunks, chunk_pages, index, embedding_model, top_k=3):
    """Return top-k chunks with a similarity score (higher = more similar)."""
    query_vec = embedding_model.encode([question])
    query_vec = np.array(query_vec).astype("float32")
    distances, indices = index.search(query_vec, top_k)

    results = []
    for dist, idx in zip(distances[0], indices[0]):
        if 0 <= idx < len(chunks):
            # FAISS L2 distance: lower = better. Convert to a rough similarity score.
            similarity = 1.0 / (1.0 + float(dist))
            results.append({
                "text": chunks[idx],
                "page": chunk_pages[idx],
                "score": similarity,
            })
    return results


# ---------- LLM ----------

def ask_llm(question, context_blocks):
    context = ""
    for block in context_blocks:
        context += f"[Page {block['page']}]\n{block['text']}\n\n"

    prompt = f"""You are a document question answering assistant.

Instructions:
1. Answer only using the context below.
2. If the answer is not present, say: "I could not find the answer in the uploaded PDF."
3. Mention the page number(s) you used as (Page X).
4. Be clear and concise.

Context:
{context}

Question:
{question}

Answer:
"""
    
    max_retries = 4
    for attempt in range(max_retries):
        try:
            response = client.models.generate_content(
                model="gemini-3.8-flash",
                contents=prompt,
            )
            return response.text
        except Exception as e:
            error_msg = str(e)
            # If Google is busy (503) or rate limiting (429), wait and retry
            if "503" in error_msg or "UNAVAILABLE" in error_msg or "429" in error_msg:
                if attempt < max_retries - 1:
                    time.sleep(3 * (attempt + 1))  # Wait 3s, then 6s, then 9s
                    continue
            
            # If it's a different error, or we ran out of retries, show a clean message
            return "The AI server is currently experiencing high traffic. Please wait a moment and try clicking your question again."
            
    return "The AI server is currently experiencing high traffic. Please wait a moment and try clicking your question again."


# ---------- UI ----------

st.set_page_config(
    page_title="RAG Document QA",
    page_icon="📄",
    layout="wide",
)

st.title("RAG Document Question Answering")
st.caption("Upload a PDF, ask questions, get answers grounded in the document with page citations.")

with st.sidebar:
    st.header("Settings")
    
    st.markdown("**How to use this tool:**")
    st.markdown("1. Upload a PDF.\n2. Ask a question.\n3. Get an answer with page numbers.")

    # Hide the complex stuff inside an expander for a cleaner UI
    with st.expander("⚙️ Advanced Retrieval Settings (Optional)"):
        chunk_size = st.slider(
            "Chunk size (characters)", 
            200, 1000, 500, 50,
            help="How big each piece of text is. Smaller chunks are faster but might lose context. Larger chunks have more context but might confuse the AI."
        )
        overlap = st.slider(
            "Chunk overlap (characters)", 
            0, 200, 100, 25,
            help="How much text chunks share with each other. Prevents sentences from getting cut in half."
        )
        top_k = st.slider(
            "Top-K chunks to retrieve", 
            1, 8, 3,
            help="How many pieces of text the AI reads to answer your question. Higher = better recall, but slower."
        )
        threshold = st.slider(
            "Similarity threshold", 
            0.0, 1.0, 0.3, 0.05,
            help="The 'I don't know' guardrail. If the AI can't find a chunk that matches your question this well, it will refuse to answer instead of guessing."
        )

    st.markdown("---")
    st.markdown("**LLM:** Gemini 3.8 Flash")
    st.markdown("**Embeddings:** all-MiniLM-L6-v2")
    st.markdown("**Vector store:** FAISS")

st.markdown("---")

uploaded_file = st.file_uploader("Upload a PDF", type=["pdf"])

embedding_model = load_embedding_model()

if uploaded_file is not None:
    st.success(f"Uploaded: {uploaded_file.name}")

    with st.spinner("Extracting text..."):
        pages = extract_text_with_pages(uploaded_file)

    if not pages:
        st.error("No readable text found in the PDF.")
    else:
        with st.spinner("Chunking..."):
            chunks, chunk_pages = split_pages_into_chunks(pages, chunk_size, overlap)

        col1, col2, col3 = st.columns(3)
        col1.metric("Pages", len(pages))
        col2.metric("Chunks", len(chunks))
        col3.metric("Avg chars / chunk",
                    int(sum(len(c) for c in chunks) / max(len(chunks), 1)))

        with st.spinner("Building vector index..."):
            index = build_vector_index(chunks, embedding_model)

        st.success("Ready. Ask a question below.")

        question = st.text_input("Your question")

        if question:
            with st.spinner("Retrieving relevant chunks..."):
                retrieved = retrieve_top_chunks(
                    question, chunks, chunk_pages, index, embedding_model, top_k
                )

            with st.expander("Retrieved chunks (with source pages and scores)"):
                for i, block in enumerate(retrieved, 1):
                    st.markdown(f"**Chunk {i} — Page {block['page']} — score {block['score']:.3f}**")
                    st.text(block["text"])
                    st.markdown("---")

            # Apply similarity threshold
            good_chunks = [r for r in retrieved if r["score"] >= threshold]

            if not good_chunks:
                st.warning(
                    "I could not find relevant information in this document to answer that question. "
                    "Try rephrasing, or check that the PDF actually contains this information."
                )
            else:
                with st.spinner("Generating answer..."):
                    answer = ask_llm(question, good_chunks)

                st.subheader("Answer")
                st.success(answer)

                pages_used = sorted({b["page"] for b in good_chunks})
                st.caption(f"Sources: pages {', '.join(map(str, pages_used))}")

st.markdown("---")
st.caption("Built by Samruddh Birajdar · Python · Streamlit · FAISS · Gemini 3.8 Flash")